// Helper to calculate summary metrics for Muamalah Awards
export const getMuamalahAwardsSummary = (awards: MuamalahAwardBadge[]) => {
  const totalBadges = awards.length;
  const unlockedBadges = awards.filter((b) => b.unlocked).length;
  const lockedBadges = totalBadges - unlockedBadges;
  const completionRatePct = Math.round((unlockedBadges / totalBadges) * 100);

  // Find next upcoming locked milestone by highest percentage
  const lockedAwardsWithRatio = awards
    .filter((b) => !b.unlocked)
    .map((b) => ({
      ...b,
      progressPct: Math.min(100, Math.round((b.currentProgress / b.targetGoal) * 100)),
      remaining: Math.max(0, b.targetGoal - b.currentProgress),
    }))
    .sort((a, b) => b.progressPct - a.progressPct);

  const nextMilestone = lockedAwardsWithRatio[0] || null;

  return {
    totalBadges,
    unlockedBadges,
    lockedBadges,
    completionRatePct,
    nextMilestone,
  };
};
